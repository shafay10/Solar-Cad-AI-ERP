/**
 * Trigger download of DXF file in browser
 */
export const downloadDxfFile = (params) => {
  const dxfString = generateAutoCadDxf(params);
  const blob = new Blob([dxfString], { type: "application/dxf;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  const filename = `${(params.projectCode || "GT-SOLAR").replace(/[^a-zA-Z0-9-_]/g, "_")}_SingleLineDiagram_SLD.dxf`;
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
};

export default { generateAutoCadDxf, downloadDxfFile };
